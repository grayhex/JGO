// Screenshots of the new UI for a visual check (not an assertion test): login, wizard steps, Settings -> library / my phones, the library list, the player tip.
// Usage: node --import tsx tests/e2e/shots-ux.mjs [outDir]
import { spawn } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { createServer } from 'node:net';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
const cwd = process.cwd();
const out = path.resolve(process.argv[2] ?? 'test-results/ux');
mkdirSync(out, { recursive: true });
const free = () => new Promise((res) => { const s = createServer(); s.listen(0, '127.0.0.1', () => { const p = s.address().port; s.close(() => res(p)); }); });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const { makeJar, put } = await import(new URL('../../apps/api/src/dev/testing.ts', import.meta.url).href);
const dir = mkdtempSync(path.join(tmpdir(), 'mgo-shots-'));
const lib = path.join(dir, 'games');
for (const n of ['Racer', 'Snake', 'Tetris', 'Bounce']) put(lib, `java/${n}.jar`, makeJar(n, { vendor: 'ACME', extra: n === 'Racer' ? 'Nokia-MIDlet-Original-Display-Size: 240,320\n' : '' }));
put(lib, 'ngage/Pandemonium (E).zip', Buffer.from('PK\x03\x04 card'));
put(lib, 'ngage/Asphalt Urban GT.zip', Buffer.from('PK\x03\x04 card2'));
put(lib, 'sis/Space Impact.sis', Buffer.from('sis fixture'));
mkdirSync(path.join(dir, 'app'));
const port = await free();
const TOKEN = 'shots-token-0123456789';
const server = spawn('node', ['apps/api/dist/server.js'], { cwd, env: { ...process.env, PORT: String(port), DATA_DIR: path.join(dir, 'app'), HOST: '127.0.0.1', LOG_LEVEL: 'warn', AUTH_TOKEN: TOKEN, LIBRARY_ROOTS: lib }, stdio: ['ignore', 'inherit', 'inherit'] });
const base = `http://127.0.0.1:${port}`;
let browser;
try {
  for (let i = 0; i < 100; i++) { try { if ((await fetch(base + '/api/health')).ok) break; } catch {} await sleep(100); }
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox'] });
  const p = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await p.goto(base);
  await p.waitForSelector('input[aria-label="Access token"]');
  await p.screenshot({ path: path.join(out, '01-login.png') });
  await p.fill('input[aria-label="Access token"]', TOKEN);
  await p.click('button:has-text("Sign in")');
  const dialog = p.getByRole('dialog', { name: 'Set up MGO' });
  await dialog.waitFor();
  await dialog.getByRole('button', { name: 'Start' }).click();
  await dialog.getByTestId('choose-j2me').waitFor();
  await p.screenshot({ path: path.join(out, '02-wizard-games.png') });
  for (const kind of ['j2me', 'ngage', 'symbian']) {
    await dialog.getByTestId(`choose-${kind}`).click();
    const pk = p.getByRole('dialog', { name: /Folder for/ });
    await pk.getByTestId('folder-check').waitFor();
    if (kind === 'j2me') await p.screenshot({ path: path.join(out, '03-folder-picker.png') });
    await pk.locator('.folder', { hasText: new RegExp(`^\\s*${kind === 'j2me' ? 'java' : kind === 'ngage' ? 'ngage' : 'sis'}$`) }).click();
    await sleep(500);
    await pk.getByTestId('folder-use').click();
    await pk.waitFor({ state: 'detached' });
  }
  await p.screenshot({ path: path.join(out, '04-wizard-games-chosen.png') });
  await dialog.getByRole('button', { name: 'Next' }).click();
  await dialog.getByTestId('my-phones').waitFor();
  await p.screenshot({ path: path.join(out, '05-wizard-phones-missing.png') });
  await dialog.getByTestId('phone-nokia-n-gage-qd').click();
  await dialog.getByTestId('phone-nokia-n95').click();
  await dialog.getByTestId('phone-sony-ericsson-k750i').click();
  await sleep(600);
  await p.screenshot({ path: path.join(out, '06-wizard-phones.png') });
  await dialog.getByTestId('wizard-next').click();
  await dialog.getByTestId('fw-unavailable').waitFor();
  await p.screenshot({ path: path.join(out, '07-wizard-firmware.png') });
  await dialog.getByRole('button', { name: 'Next / skip' }).click();
  await dialog.getByRole('button', { name: 'Next' }).click();
  await dialog.getByRole('button', { name: 'Next' }).click();
  await dialog.locator('.wizard-body[data-step=done]').waitFor();
  await p.screenshot({ path: path.join(out, '08-wizard-done.png') });
  await dialog.getByRole('button', { name: 'Finish' }).click();
  await p.locator('.game-card').first().waitFor();
  await sleep(2500);
  await p.screenshot({ path: path.join(out, '09-library-list.png') });
  await p.getByRole('radio', { name: 'Tiles' }).click();
  await sleep(300);
  await p.screenshot({ path: path.join(out, '10-library-tiles.png') });
  await p.getByRole('radio', { name: 'List' }).click();
  await p.goto(base + '/settings#library');
  await p.getByTestId('library-folders').waitFor();
  await sleep(500);
  await p.screenshot({ path: path.join(out, '11-settings-library.png') });
  await p.goto(base + '/settings#phone');
  await p.getByTestId('my-phones').waitFor();
  await sleep(400);
  await p.screenshot({ path: path.join(out, '12-settings-phones.png'), fullPage: true });
  await p.goto(base + '/settings#mobygames');
  await sleep(1500);
  await p.screenshot({ path: path.join(out, '13-settings-metadata.png') });
  await p.goto(base + '/phones');
  await p.locator('.phone-pick').first().waitFor();
  await sleep(800);
  await p.screenshot({ path: path.join(out, '14-phones.png') });
  const games = await (await fetch(base + '/api/games', { headers: { authorization: `Bearer ${TOKEN}` } })).json();
  const racer = games.find((g) => g.name === 'Racer');
  await fetch(base + `/api/games/${racer.id}`, { method: 'PATCH', headers: { authorization: `Bearer ${TOKEN}`, 'content-type': 'application/json' }, body: JSON.stringify({ settings: { skinId: 'nokia-n-gage-qd' } }) });
  await p.goto(base + '/play/' + racer.id);
  await p.locator('.skin-box').waitFor();
  await sleep(1200);
  await p.screenshot({ path: path.join(out, '15-player-tip.png') });
  console.log('screenshots in', out);
} finally {
  await browser?.close();
  server.kill('SIGTERM');
  rmSync(dir, { recursive: true, force: true });
}
